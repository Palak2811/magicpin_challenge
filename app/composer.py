def research_digest(ctx: Ctx) -> Draft:
    item = digest_item(ctx.category, ctx.payload.get("top_item_id") or ctx.payload.get("digest_item_id"),
                       kinds=("research", "trend", "tech"))
    if not item:
        return generic(ctx)
    src = item.get("source", "")
    seg = humanize(item.get("patient_segment")) if item.get("patient_segment") else ""
    trial = f"{num(item['trial_n'])}-patient trial: " if item.get("trial_n") else ""
    tie = ""
    hr = g(ctx.merchant, "customer_aggregate", "high_risk_adult_count")
    if seg and "high-risk" in seg and hr:
        tie = f"Directly relevant to the {num(hr)} high-risk adults on your roster."
    elif seg:
        tie = f"Most relevant if you see a lot of {seg}."
    opener = f"{ctx.sal}, new in {src.split(',')[0]} —" if src else f"{ctx.sal}, one research item this week —"
    fact = _join(f"{item.get('title', '')}.", f"{trial}{first_sentence(item.get('summary'))}", tie)
    deliverable = "the 2-min abstract summary + a patient-education WhatsApp you can forward"
    cta = _ask(ctx, deliverable, f"Want me to pull {deliverable}?", "ready kar")
    if src:
        cta = f"{cta} — {src}"
    return _draft(ctx, opener, fact, cta, "binary_yes_no",
                  f"External research digest ({src}) matched to merchant's patient mix; source cited for credibility; reciprocity CTA.",
                  deliverable)


