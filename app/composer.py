def _diagnosis(ctx: Ctx) -> list[str]:
    reasons = []
    stale = signal_value(ctx.merchant, "stale_posts")
    if stale is not None:
        reasons.append(f"last Google post was {stale.replace('d', ' days')} ago" if stale else "Google posts are stale")
    if has_signal(ctx.merchant, "no_active_offers") or not active_offers(ctx.merchant):
        reasons.append("no active offer on your listing")
    if has_signal(ctx.merchant, "unverified_gbp") or g(ctx.merchant, "identity", "verified") is False:
        reasons.append("your Google profile is still unverified")
    if has_signal(ctx.merchant, "no_recent_post"):
        reasons.append("no recent Google post")
    return reasons


def perf_dip(ctx: Ctx) -> Draft:
    p = ctx.payload
    metric, delta = p.get("metric"), p.get("delta_pct")
    if is_placeholder(ctx.trigger) or metric is None:
        d7 = g(ctx.merchant, "performance", "delta_7d") or {}
        pairs = [(k.replace("_pct", ""), v) for k, v in d7.items() if isinstance(v, (int, float))]
        pairs.sort(key=lambda kv: kv[1])
        metric, delta = (pairs[0] if pairs else ("views", None))
    base = p.get("vs_baseline")
    cur = ctx.perf(metric)
    if delta is not None and delta < 0:
        opener = f"{ctx.sal}, your {metric} are down {pct(delta)} this week"
    elif delta is not None:
        opener = f"{ctx.sal}, {metric} is your slowest metric this week (only +{pct(delta)})"
    else:
        opener = f"{ctx.sal}, your {metric} have slowed this week"
    opener += f" (baseline ~{base}/week)." if base else (f" — {num(cur)} in the last 30 days." if cur is not None else ".")
    # one driving signal: the single biggest fixable cause (judging guidance: don't stack every fact)
    reasons = _diagnosis(ctx)
    offer = active_offers(ctx.merchant)
    primary = reasons[0] if reasons else ""
    if primary:
        fact = f"The biggest fixable gap I can see: {primary}."
    else:
        peer_ctr = ctr_vs_peer(ctx.merchant, ctx.category)
        fact = (peer_ctr[0].upper() + peer_ctr[1:] + ".") if peer_ctr else ""
    if "offer" in primary or not offer:
        fix, en_verb, hi_verb = (f"an offer like {catalog_offer(ctx.category)} plus a Google post announcing it",
                                 "set up", "aaj hi set up kar")
    elif "unverified" in primary:
        fix, en_verb, hi_verb = "the 5-minute Google verification steps", "walk you through", "aaj hi karwa"
    else:
        fix, en_verb, hi_verb = f"a fresh Google post pushing {offer[0]}", "draft", "aaj hi draft kar"
    deliverable = fix
    cta = _ask(ctx, fix, f"Want me to {en_verb} {fix} today?", hi_verb)
    return _draft(ctx, opener, fact, cta, "binary_yes_no",
                  f"Internal perf dip on {metric}; picks the single biggest fixable cause from merchant signals and one matching fix.",
                  deliverable)


def perf_spike(ctx: Ctx) -> Draft:
    p = ctx.payload
    metric, delta = p.get("metric"), p.get("delta_pct")
    if is_placeholder(ctx.trigger) or metric is None:
        d7 = g(ctx.merchant, "performance", "delta_7d") or {}
        pairs = [(k.replace("_pct", ""), v) for k, v in d7.items() if isinstance(v, (int, float))]
        pairs.sort(key=lambda kv: -kv[1])
        metric, delta = (pairs[0] if pairs else ("views", None))
    driver = humanize(p.get("likely_driver")) if p.get("likely_driver") else ""
    base = p.get("vs_baseline")
    if delta is not None and delta > 0:
        opener = f"{ctx.sal}, nice — {metric} up {pct(delta)} this week"
    else:
        opener = f"{ctx.sal}, your {metric} are holding steady this week"
    opener += (f" vs your ~{base}/week baseline" if base else "") + (f", most likely from your {driver}." if driver else ".")
    cur, peer_key = ctx.perf(metric), f"avg_{metric}_30d"
    peer = ctx.peer(peer_key)
    fact = ""
    if cur is not None and peer:
        if cur >= peer:
            fact = (f"That puts you level with the {num(peer)}-{metric.rstrip('s')} peer average." if cur == peer
                    else f"You're at {num(cur)} {metric} in 30 days — ahead of the {num(peer)} peer average.")
        else:
            fact = f"You're at {num(cur)} {metric} in 30 days; the peer average is {num(peer)} — this spike is how you close the gap."
    fact = _join(fact, "Momentum fades in ~7 days unless you follow up.")
    offer = active_offers(ctx.merchant)
    deliverable = f"a follow-up post" + (f" featuring {offer[0]}" if offer else "") + " while the traffic is warm"
    cta = _ask(ctx, deliverable, f"Want me to draft {deliverable}?", "draft kar")
    return _draft(ctx, opener, fact, cta, "binary_yes_no",
                  "Perf spike — reinforce what worked, quantify vs peers, and convert momentum with one follow-up post.",
                  deliverable)


