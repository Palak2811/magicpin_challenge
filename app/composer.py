        metric = metric if metric.endswith("s") else metric + "s"
        now_v, target = p.get("value_now"), p.get("milestone_value")
        gap = (target - now_v) if isinstance(now_v, int) and isinstance(target, int) else None
        if p.get("is_imminent") and gap and gap > 0:
            opener = f"{ctx.sal}, you're {gap} {metric} away from {num(target)} — currently at {num(now_v)}."
