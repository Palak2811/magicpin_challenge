def _apply_regional_greeting(draft: Draft, ctx: Ctx, send_as: str) -> None:
    """Tamil / Telugu / Kannada / Marathi-first recipients get a greeting in their language; facts stay in English."""
    if send_as == "merchant_on_behalf":
        word = customer_regional_greeting(ctx.customer)
        if word and not g(ctx.customer, "identity", "senior_citizen"):
            if draft.body.startswith("Hi "):
                draft.body = word + draft.body[2:]
            elif draft.body.startswith("Hi,"):
                draft.body = word + draft.body[2:]
    else:
        word = merchant_regional_greeting(ctx.merchant)
        if word and ctx.sal and draft.body.startswith(ctx.sal):
            draft.body = f"{word} {draft.body}"
            if draft.template_params:
                draft.template_params[0] = f"{word} {draft.template_params[0]}"


def compose_draft(category: dict, merchant: dict, trigger: dict, customer: Optional[dict] = None,
                  now: Optional[str] = None) -> tuple[Draft, str, str]:
    """Returns (draft, send_as, template_name)."""
    category = category or {}
    merchant = merchant or {}
    trigger = trigger or {}
    slug = str(merchant.get("category_slug") or category.get("slug") or "")
    kind = str(trigger.get("kind") or "")
    customer_scope = trigger.get("scope") == "customer" or kind in CUSTOMER_HANDLERS
    ctx = Ctx(category=category, merchant=merchant, trigger=trigger, customer=customer, now=now, slug=slug,
              sal=merchant_salutation(merchant, slug),
              hi=customer_prefers_hinglish(customer) if customer_scope else merchant_prefers_hinglish(merchant),
              payload=trigger.get("payload") if isinstance(trigger.get("payload"), dict) else {})
    if customer_scope and customer:
        handler = CUSTOMER_HANDLERS.get(kind, customer_generic)
        send_as = "merchant_on_behalf"
    else:
        handler = MERCHANT_HANDLERS.get(kind, generic)
        send_as = "vera"
    try:
        draft = handler(ctx)
    except Exception:  # never fail a tick because of one malformed context
        draft = customer_generic(ctx) if send_as == "merchant_on_behalf" else generic(ctx)
    _apply_regional_greeting(draft, ctx, send_as)
    draft.body = strip_taboos(draft.body, category) if "\n" not in draft.body else draft.body
    draft.body = re.sub(r"\s*(https?://\S+|www\.\S+)", "", draft.body)  # URLs are rejected by Meta (-3)
    return draft, send_as, TEMPLATE_NAMES.get(kind, "vera_generic_v1" if send_as == "vera" else "merchant_generic_v1")


def compose(category: dict, merchant: dict, trigger: dict, customer: Optional[dict] = None,
            now: Optional[str] = None) -> dict:
    """Challenge contract (§7.1): returns body, cta, send_as, suppression_key, rationale (+ template info)."""
    draft, send_as, template_name = compose_draft(category, merchant, trigger, customer, now)
    return {
        "body": draft.body,
        "cta": draft.cta,
        "send_as": send_as,
        "suppression_key": str((trigger or {}).get("suppression_key") or f"{(trigger or {}).get('kind')}:{(merchant or {}).get('merchant_id')}"),
        "rationale": draft.rationale,
        "template_name": template_name,
        "template_params": draft.template_params,
        "deliverable": draft.deliverable,
    }
