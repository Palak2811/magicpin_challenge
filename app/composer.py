_SKIP_KEYS = {"placeholder", "merchant_id", "customer_id", "category", "id", "metric_or_topic"}


def payload_facts(payload: dict, limit: int = 3) -> list[str]:
    """Readable 'why now' facts from an unknown trigger payload: scalar fields only, never invented."""
    out = []
    for k, v in payload.items():
        if k in _SKIP_KEYS or k.endswith("_id") or isinstance(v, (dict, list)) or v in (None, "", True, False):
            continue
        label = humanize(k).replace(" pct", "").replace(" iso", "")
        if isinstance(v, float) and -1 <= v <= 1 and ("pct" in k or "delta" in k):
            val = ("+" if v > 0 else "-") + pct(v)
        elif isinstance(v, str) and re.match(r"^\d{4}-\d{2}-\d{2}", v):
            val = fmt_day(v) if "T" in v else fmt_date(v)
        else:
            val = humanize(v) if isinstance(v, str) and "_" in v else str(v)
        out.append(f"{label}: {val}")
        if len(out) >= limit:
            break
    return out


