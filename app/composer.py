"""Deterministic message composer: compose(category, merchant, trigger, customer?) -> message.

Routing is by trigger.kind. Every handler:
  * anchors on facts that exist in the pushed contexts (never invents numbers, names, prices),
  * states "why now" from the trigger,
  * personalises with the merchant's own numbers/offers/history,
  * ends with a single low-friction CTA.

Triggers generated by the dataset tool carry `{"placeholder": true}` payloads; handlers then fall back
to the merchant's real performance/offer/signal data rather than inventing trigger details.
"""
from __future__ import annotations

import re

from dataclasses import dataclass, field
from typing import Any, Callable, Optional

